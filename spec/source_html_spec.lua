local html = require("rfc.source.html")

describe("decode", function()
    it("decodes the named and numeric entities a report uses", function()
        assert.are.equal("a & b < c > \"d\" 'e'", html.decode("a &amp; b &lt; c &gt; &quot;d&quot; &apos;e&apos;"))
        assert.are.equal("it’s … — – → ©", html.decode("it&#8217;s &hellip; &mdash; &ndash; &rarr; &copy;"))
        assert.are.equal("A B", html.decode("A&nbsp;B"))
        assert.are.equal("x &unknown; y", html.decode("x &unknown; y"))
        assert.are.equal("é", html.decode("&#xe9;"))
    end)
end)

describe("squash", function()
    it("folds whitespace runs and trims", function()
        assert.are.equal("a b c", html.squash("  a\n  b\t\tc \n"))
    end)
end)

describe("tokens", function()
    it("reads open, text and close tokens with the attributes that matter", function()
        local t = html.tokens({ '<p class="note" id="n1">Hi <a href="#x">there</a></p>' })
        assert.are.same({ kind = "open", name = "p", attrs = { class = "note", id = "n1" }, line = 1 }, t[1])
        assert.are.same({ kind = "text", text = "Hi ", line = 1 }, t[2])
        assert.are.same({ kind = "open", name = "a", attrs = { href = "#x" }, line = 1 }, t[3])
        assert.are.same({ kind = "text", text = "there", line = 1 }, t[4])
        assert.are.same({ kind = "close", name = "a", line = 1 }, t[5])
        assert.are.same({ kind = "close", name = "p", line = 1 }, t[6])
    end)
    it("marks void and self-closed elements, and keeps attribute values across lines", function()
        local t = html.tokens({ "<img src=", '"images/a.png" alt="An example"><br/><hr>' })
        assert.are.same(
            { kind = "open", name = "img", attrs = { src = "images/a.png", alt = "An example" }, void = true, line = 1 },
            t[1]
        )
        assert.is_true(t[2].void and t[3].void)
    end)
    it("skips comments, script and style whole, and keeps text whitespace as written", function()
        local t = html.tokens({ "<!-- c --><script>var x = '<p>';</script><style>p{}</style><pre>a", "  b</pre>" })
        assert.are.same({ kind = "open", name = "pre", attrs = {}, line = 1 }, t[1])
        assert.are.same({ kind = "text", text = "a\n  b", line = 1 }, t[2])
    end)
    it("reads an unquoted attribute and an uppercase tag", function()
        local t = html.tokens({ "<TD colspan=2 class=x>v</TD>" })
        assert.are.same({ kind = "open", name = "td", attrs = { class = "x" }, line = 1 }, t[1])
    end)
    it("reads a custom element as any other", function()
        local t = html.tokens({ "<c- c>/**</c->" })
        assert.are.equal("c-", t[1].name)
        assert.are.equal("close", t[3].kind)
    end)
    it("keeps greater-than signs inside either kind of quoted attribute", function()
        local t = html.tokens({ [[<abbr title="a > b" id='x>y'>X</abbr>]] })
        assert.are.same({ title = "a > b", id = "x>y" }, t[1].attrs)
        assert.are.equal("X", t[2].text)
        assert.are.equal("close", t[3].kind)
        local b = html.blocks({ [[<p><abbr title="a > b">X</abbr></p>]] })
        assert.are.equal("X (a > b)", b[1].text.text)
    end)
end)
