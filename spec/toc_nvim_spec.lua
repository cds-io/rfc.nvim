-- The contents sidebar. Runs inside Neovim (make test-nvim).
local editor = require("spec.editor")
local toc = require("rfc.toc")

local function feed(keys)
    vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(keys, true, false, true), "x", false)
end

local function rows(side)
    return vim.api.nvim_buf_get_lines(vim.api.nvim_win_get_buf(side), 0, -1, false)
end

--- The cursor in the document window, then the move the reader's loop reports.
local function move(doc_win, line)
    vim.api.nvim_set_current_win(doc_win)
    vim.api.nvim_win_set_cursor(doc_win, { line, 0 })
    vim.api.nvim_exec_autocmds("CursorMoved", { buffer = vim.api.nvim_win_get_buf(doc_win) })
end

describe("the contents sidebar", function()
    local case, restore, doc_win

    setup(function()
        editor.load_plugin()
    end)

    before_each(function()
        case, restore = editor.start()
        vim.cmd("Rfc 9110")
        assert.is_true(editor.wait_help("9110"))
        doc_win = vim.api.nvim_get_current_win()
    end)

    after_each(function()
        restore()
    end)

    it("opens on gO beside the document, one row per heading, and takes the cursor", function()
        feed("gO")
        local side = toc.window(doc_win)
        assert.is_truthy(side)
        assert.are.equal(side, vim.api.nvim_get_current_win())
        assert.are.equal(44, vim.api.nvim_win_get_width(side))
        assert.are.equal("rfc-toc", vim.bo[vim.api.nvim_win_get_buf(side)].filetype)
        local lines = rows(side)
        assert.are.equal(305, #lines)
        assert.are.equal("1.  Introduction", lines[1])
        assert.are.equal("  1.1.  Purpose", lines[2])
        assert.is_true(vim.tbl_contains(lines, "      5.6.1.1.  Sender Requirements"))
        assert.is_true(vim.wo[side].winfixwidth)
        assert.is_true(vim.wo[side].cursorline)
    end)

    it("indents a proposal's headings by their level", function()
        vim.cmd("Eip 1559")
        assert.is_true(editor.wait_help("eip1559"))
        feed("gO")
        local lines = rows(toc.window(doc_win))
        assert.are.equal(13, #lines)
        assert.are.equal("ABSTRACT", lines[2])
        assert.are.equal("  Block Hash Changing", lines[6])
    end)

    it("keeps its cursor on the row of the section the reader is in", function()
        feed("gO")
        local side = toc.window(doc_win)
        move(doc_win, 383)
        assert.are.equal(2, vim.api.nvim_win_get_cursor(side)[1])
        move(doc_win, 10785)
        assert.are.equal(305, vim.api.nvim_win_get_cursor(side)[1])
        move(doc_win, 1)
        assert.are.equal(305, vim.api.nvim_win_get_cursor(side)[1])
    end)

    it("jumps the document to a row's section on Enter, through the tag stack", function()
        feed("gO")
        local side = toc.window(doc_win)
        local depth = vim.fn.gettagstack(doc_win).length
        vim.api.nvim_win_set_cursor(side, { 2, 0 })
        feed("<CR>")
        assert.are.equal(doc_win, vim.api.nvim_get_current_win())
        assert.are.equal(383, vim.fn.line("."))
        assert.are.equal(depth + 1, vim.fn.gettagstack(doc_win).length)
        feed("<C-t>")
        assert.are.equal(1, vim.fn.line("."))
    end)

    it("closes on gO in the document", function()
        feed("gO")
        local side = toc.window(doc_win)
        vim.api.nvim_set_current_win(doc_win)
        feed("gO")
        assert.is_false(vim.api.nvim_win_is_valid(side))
        assert.is_nil(toc.window(doc_win))
    end)

    it("closes on q or gO in the sidebar", function()
        feed("gO")
        local side = toc.window(doc_win)
        feed("q")
        assert.is_false(vim.api.nvim_win_is_valid(side))
        vim.api.nvim_set_current_win(doc_win)
        feed("gO")
        side = toc.window(doc_win)
        feed("gO")
        assert.is_false(vim.api.nvim_win_is_valid(side))
    end)

    it("closes with the document window", function()
        feed("gO")
        local side = toc.window(doc_win)
        vim.api.nvim_win_close(doc_win, true)
        assert.is_true(vim.wait(500, function()
            return not vim.api.nvim_win_is_valid(side)
        end))
        assert.is_nil(toc.window(doc_win))
    end)

    it("outlives a :q on the document that was the last window, holding an empty buffer", function()
        vim.cmd("only")
        feed("gO")
        vim.api.nvim_set_current_win(doc_win)
        vim.cmd("quit")
        -- the sidebar's turn comes on the next pass of the loop
        assert.is_true(vim.wait(500, function()
            local wins = vim.api.nvim_tabpage_list_wins(0)
            return #wins == 1 and vim.bo[vim.api.nvim_win_get_buf(wins[1])].filetype ~= "rfc-toc"
        end))
        local win = vim.api.nvim_tabpage_list_wins(0)[1]
        assert.is_false(vim.wo[win].winfixwidth)
        assert.is_nil(toc.window(doc_win))
    end)

    it("counts a floating window as no window when the document was the last", function()
        vim.cmd("only")
        feed("gO")
        local side = toc.window(doc_win)
        -- a notifier's toast, say, open while the document closes
        local float = vim.api.nvim_open_win(vim.api.nvim_create_buf(false, true), false, {
            relative = "editor",
            width = 12,
            height = 2,
            row = 1,
            col = 1,
        })
        vim.api.nvim_set_current_win(doc_win)
        vim.cmd("quit")
        assert.is_true(vim.wait(500, function()
            return vim.api.nvim_win_is_valid(side) and vim.bo[vim.api.nvim_win_get_buf(side)].filetype ~= "rfc-toc"
        end))
        assert.is_false(vim.wo[side].winfixwidth)
        vim.api.nvim_win_close(float, true)
    end)

    it("follows CTRL-] into another document", function()
        feed("gO")
        local side = toc.window(doc_win)
        move(doc_win, 5648) -- Section |rfc2616-14.4| of |rfc2616|
        vim.api.nvim_win_set_cursor(doc_win, { 5648, 48 })
        feed("<C-]>")
        assert.is_true(editor.wait_help("2616"))
        assert.are.same({ "9110", "2616" }, case.fetched)
        assert.are.equal(253, #rows(side))
        assert.are.equal("1 Introduction", rows(side)[1])
        vim.api.nvim_exec_autocmds("CursorMoved", { buffer = 0 })
        assert.are.equal(5785, vim.fn.line("."))
        assert.is_true(vim.api.nvim_win_get_cursor(side)[1] > 1)
    end)

    it("reads the new rows when the subjects document is rendered again on a status", function()
        vim.cmd("Eip subjects")
        assert.is_true(editor.wait_help("eip-subjects"))
        doc_win = vim.api.nvim_get_current_win()
        feed("gO")
        local side = toc.window(doc_win)
        assert.is_true(vim.tbl_contains(rows(side), "  Living  (3)"))
        vim.api.nvim_set_current_win(doc_win)
        vim.cmd("Eip status final")
        assert.is_true(vim.wait(1000, function()
            return vim.api.nvim_buf_get_lines(0, 0, 1, false)[1]:match("%[Status: Final%]") ~= nil
        end))
        assert.are.equal(doc_win, vim.api.nvim_get_current_win())
        assert.are.equal(side, toc.window(doc_win))
        local lines = rows(side)
        assert.is_false(vim.tbl_contains(lines, "  Living  (3)"))
        assert.is_true(vim.tbl_contains(lines, "  Final  (5)"))
        assert.is_true(vim.tbl_contains(lines, "Core  (2)"))
    end)

    it("closes when the document window turns to something else", function()
        feed("gO")
        local side = toc.window(doc_win)
        vim.api.nvim_win_call(doc_win, function()
            vim.cmd("help motion.txt")
        end)
        assert.is_true(vim.wait(500, function()
            return not vim.api.nvim_win_is_valid(side)
        end))
    end)
end)
