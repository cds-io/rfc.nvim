local cache = require("rfc.cache")

describe("fresh", function()
    it("is a file younger than max_age", function()
        assert.is_true(cache.fresh(100, 150, 60))
        assert.is_false(cache.fresh(100, 160, 60))
        assert.is_false(cache.fresh(100, 161, 60))
    end)
    it("is not fresh when the index dates the thing after the copy", function()
        assert.is_false(cache.fresh(100, 150, nil, 120))
        assert.is_true(cache.fresh(100, 150, nil, 90))
        assert.is_true(cache.fresh(100, 150, 60, nil))
    end)
    it("never ages without a max_age, and is never a missing file", function()
        assert.is_true(cache.fresh(1, 1e9, nil))
        assert.is_false(cache.fresh(nil, 1, nil))
        assert.is_false(cache.fresh(nil, 1, 60))
    end)
end)

describe("current", function()
    it("is a document by the current version no older than each input", function()
        assert.is_true(cache.current(100, true, { 100, 90 }))
        assert.is_false(cache.current(100, true, { 101 }))
        assert.is_false(cache.current(100, false, { 90 }))
    end)
    it("is never a missing document or a missing input", function()
        assert.is_false(cache.current(nil, true, { 90 }))
        assert.is_false(cache.current(100, true, { false }))
        assert.is_false(cache.current(100, true, { 90, false }))
    end)
    it("holds with no inputs", function()
        assert.is_true(cache.current(100, true, {}))
    end)
end)
